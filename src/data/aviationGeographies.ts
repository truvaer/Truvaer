export const ALL_ZONES: AviationZone[] = ['APAC', 'ANZ', 'CIS', 'EMEA', 'LATAM', 'NA'];

export const getCountriesForZone = (zone: AviationZone | 'All'): string[] => {
  if (zone === 'All') {
    const set = new Set<string>();
    ALL_ZONES.forEach((z) => {
      AVIATION_ZONES_MAP[z].countries.forEach((c) => set.add(c));
    });
    return Array.from(set).sort();
  }
  return AVIATION_ZONES_MAP[zone]?.countries || [];
};

export const getZoneForCountry = (country: string): AviationZone => {
  const norm = country.trim().toLowerCase();
  for (const zone of ALL_ZONES) {
    const list = AVIATION_ZONES_MAP[zone].countries;
    if (list.some((c) => c.toLowerCase() === norm || norm.includes(c.toLowerCase()) || c.toLowerCase().includes(norm))) {
      return zone;
    }
  }
  return 'APAC';
};

